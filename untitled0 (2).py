"""### 4. Error Reduction & Advanced Accuracy Evaluation
To stabilize our accuracy and reduce overfitting errors caused by having a tiny dataset (10 rows), we will:
1. Limit the maximum depth of the Decision Tree to simplify decision boundaries.
2. Evaluate model stability using Leave-One-Out Cross-Validation (LOOCV) to test on every single row dynamically.
"""

from sklearn.model_selection import LeaveOneOut
from sklearn.metrics import classification_report, accuracy_score

# Configure LOOCV
loo = LeaveOneOut()
y_true_all = []
y_pred_all = []

# Loop through each sample as a test set (LOOCV)
for train_idx, test_idx in loo.split(X):
    X_tr, X_te = X.iloc[train_idx], X.iloc[test_idx]
    y_tr, y_te = y.iloc[train_idx], y.iloc[test_idx]

    # Use a highly regularized Decision Tree (shallow depth) to reduce generalization error
    optimized_dt = DecisionTreeClassifier(max_depth=2, random_state=42)
    optimized_dt.fit(X_tr, y_tr)

    y_true_all.append(y_te.values[0])
    y_pred_all.append(optimized_dt.predict(X_te)[0])

# Evaluate the error-reduced model
loocv_accuracy = accuracy_score(y_true_all, y_pred_all)
print(f"Optimized Decision Tree LOOCV Accuracy (Robust Evaluation): {loocv_accuracy * 100:.2f}%")
print("\n--- Robust Classification Report (LOOCV) ---")
